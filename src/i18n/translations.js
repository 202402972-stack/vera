const patterns = [];
export function translate(value, language) {
  if (language !== "ar" || typeof value !== "string") return value;
  const trimmed = value.replace(/\s+/g, " ").trim();
  let translated = translations[trimmed];
  if (!translated) {
    for (const { regex, text } of patterns) {
      const match = trimmed.match(regex);
      if (match) {
        translated = text.replace(/\{(\d+)\}/g, (_, n) =>
          translate(match[Number(n) + 1] || "", language),
        );
        break;
      }
    }
  }
  if (!translated) return value;
  const before = value.match(/^\s*/)[0],
    after = value.match(/\s*$/)[0];
  return before + translated + after;
}
export function buildPatterns() {
  patterns.length = 0;
  for (const [key, text] of Object.entries(translations)) {
    if (!/\{\d+\}/.test(key)) continue;
    const escaped = key
      .split(/\{\d+\}/)
      .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
      .join("(.+?)");
    patterns.push({ regex: new RegExp(`^${escaped}$`), text });
  }
}

